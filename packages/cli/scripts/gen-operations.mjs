#!/usr/bin/env node
// Build src/generated/operations.ts from ../../spec/openapi.v2.json: one entry
// per operation with its CLI name (the spec's `x-vistalink-cli`), path/query
// params, top-level body fields (with the value kind the docs grammar uses to
// parse a flag), whether it takes an `Idempotency-Key` header and its
// `x-vistalink-kind` / `x-vistalink-scope`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(resolve(here, "../../../spec/openapi.v2.json"), "utf8"));

const deref = (node) => {
  let n = node;
  while (n && n.$ref) n = n.$ref.split("/").slice(1).reduce((o, k) => o[k], spec);
  return n ?? {};
};

/** scalar | number | integer | boolean | list | string_or_json | json */
function kindOf(schema) {
  let s = deref(schema);
  if (s.anyOf || s.oneOf) {
    const opts = (s.anyOf ?? s.oneOf).map(deref).filter((x) => x.type !== "null");
    // A bare word or an object (price_to_beat: "auto" | {total, currency}).
    if (opts.length > 1 && opts.some((x) => x.type === "string")) return "string_or_json";
    if (opts.length !== 1) return "json";
    s = opts[0];
  }
  const t = Array.isArray(s.type) ? s.type.find((x) => x !== "null") : s.type;
  if (t === "integer" || t === "number" || t === "boolean") return t;
  if (t === "string") return "string";
  if (t === "array") {
    const it = deref(s.items ?? {});
    const itemTypes = (it.anyOf ?? it.oneOf ?? [it]).map(deref).map((x) => x.type);
    return itemTypes.every((x) => ["string", "integer", "number"].includes(x)) ? "list" : "list_or_json";
  }
  return "json";
}

const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const op = item[method];
    if (!op) continue;
    const key = `${method.toUpperCase()} ${path}`;
    const cli = op["x-vistalink-cli"]?.replace(/^vistalink /, "");
    if (!cli || cli.split(" ").length !== 2) throw new Error(`${key}: x-vistalink-cli must be "vistalink <group> <verb>" (got ${op["x-vistalink-cli"]})`);
    const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(deref);
    const idem = params.find((p) => p.in === "header" && p.name.toLowerCase() === "idempotency-key");
    const security = op.security ?? spec.security ?? [];
    const bodySchema = deref(op.requestBody?.content?.["application/json"]?.schema);
    const required = new Set(bodySchema.required ?? []);
    ops.push({
      key,
      cli,
      method: method.toUpperCase(),
      path,
      summary: op.summary ?? "",
      pathParams: params.filter((p) => p.in === "path").map((p) => p.name),
      query: params.filter((p) => p.in === "query").map((p) => ({ name: p.name, kind: kindOf(p.schema ?? {}), description: p.description ?? "" })),
      body: op.requestBody
        ? Object.entries(bodySchema.properties ?? {}).map(([name, s]) => ({
            name,
            kind: kindOf(s),
            required: required.has(name),
            description: (deref(s).description ?? s.description ?? "").split("\n")[0].slice(0, 120),
          }))
        : null,
      idempotent: !!idem,
      idempotencyRequired: !!idem?.required,
      kind: op["x-vistalink-kind"] ?? "sync",
      scope: op["x-vistalink-scope"] ?? null,
      public: security.length === 0,
    });
  }
}

const out = `// Generated by scripts/gen-operations.mjs from spec/openapi.v2.json. Do not edit.
export type FieldKind = "string" | "integer" | "number" | "boolean" | "list" | "list_or_json" | "string_or_json" | "json";
export interface OperationField { name: string; kind: FieldKind; required?: boolean; description: string }
export interface Operation {
  key: string;
  cli: string;
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  summary: string;
  pathParams: string[];
  query: OperationField[];
  body: OperationField[] | null;
  /** Declares an \`Idempotency-Key\` header parameter. */
  idempotent: boolean;
  /** ...and requires it (bookings). Optional ones are generated only when the call starts a job. */
  idempotencyRequired: boolean;
  /** x-vistalink-kind: \`sync\` or \`job\` (202). */
  kind: string;
  /** x-vistalink-scope */
  scope: string | null;
  public: boolean;
}
export const SPEC_VERSION = ${JSON.stringify(spec.info.version)};
export const OPERATIONS: Operation[] = ${JSON.stringify(ops, null, 2)};
`;
writeFileSync(resolve(here, "../src/generated/operations.ts"), out);
console.log(`cli: ${ops.length} operations → src/generated/operations.ts`);
